// Bundles the teachers' read-only page into one self-contained HTML file (viewer/index.html),
// which the Apps Script web app fetches from GitHub. Run: node term2-planner/tools/build-viewer.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const dir = new URL("../", import.meta.url);
const read = (p) => readFileSync(new URL(p, dir), "utf8");
const MODULES = ["logic.js", "sheet-format.js", "summary.js", "viewer-app.js"];
const varName = (file) => "__" + file.replace(/\W/g, "_");

// Each ES module becomes a function scope returning its exports; imports become destructuring.
function wrap(file) {
  const src = read(file);
  const names = [...src.matchAll(/^export (?:async )?(?:const|function) (\w+)/gm)].map((m) => m[1]);
  const body = src
    .replace(/^import \* as (\w+) from "\.\/(.+?)";$/gm, (_, ns, f) => `const ${ns} = ${varName(f)};`)
    .replace(/^import \{(.+?)\} from "\.\/(.+?)";$/gm, (_, list, f) => `const {${list.replace(/ as /g, ": ")}} = ${varName(f)};`)
    .replace(/^export /gm, "");
  return `const ${varName(file)} = (() => {\n${body}\nreturn { ${names.join(", ")} };\n})();`;
}

export function buildViewer() {
  const style = /<style>[\s\S]*?<\/style>/.exec(read("index.html"))[0];
  const extra = `<style>
.view-row { display: grid; gap: var(--s1); cursor: default; }
.view-row:hover { background: transparent; }
.view-row .t2 { display: grid; gap: 2px; }
.view-row .t2 .label { font-size: .8125rem; font-weight: 500; color: var(--muted); }
.view-row .topics { display: flex; flex-wrap: wrap; gap: 2px var(--s3); }
.view-row .topics b { font-weight: 500; color: var(--muted); font-variant-numeric: tabular-nums; margin-right: 4px; }
</style>`;
  const script = MODULES.map(wrap).join("\n\n");
  return `<!doctype html>
<html lang="th">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">
<title>เนื้อหาคณิตเทอม 2</title>
<!-- Generated by tools/build-viewer.mjs — edit the source modules, then rebuild. -->
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=IBM+Plex+Sans+Thai:wght@400;500;600&display=swap">
${style}
${extra}
</head>
<body>
<main class="wrap" id="app" aria-live="polite"></main>
<script src="https://cdnjs.cloudflare.com/ajax/libs/html2canvas/1.4.1/html2canvas.min.js"></script>
<script>
(() => {
${script}
})();
</script>
</body>
</html>
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(new URL("viewer/index.html", dir), buildViewer());
  console.log("wrote viewer/index.html");
}
